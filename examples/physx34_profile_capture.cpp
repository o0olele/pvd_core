namespace {
using namespace physx;
namespace wire = physx::pvdsdk;
namespace cpu = physx::profile;
void require(bool value, const char *message) {
  if (!value)
    throw std::runtime_error(message);
}
void checked(wire::PvdError value) {
  require(value == wire::PvdErrorType::Success,
          "PvdDataStream operation failed");
}
struct Assertions final : PxAssertHandler {
  void operator()(const char *expression, const char *file, int line,
                  bool &) override {
    std::fprintf(stderr, "PhysX assertion: %s (%s:%d)\n", expression, file,
                 line);
    std::fflush(nullptr);
    std::_Exit(3);
  }
};
struct Errors final : PxErrorCallback {
  unsigned failures = 0;
  void reportError(PxErrorCode::Enum code, const char *message,
                   const char *file, int line) override {
    std::fprintf(stderr, "PhysX [%d] %s (%s:%d)\n", int(code), message, file,
                 line);
    if (code != PxErrorCode::eDEBUG_INFO && code != PxErrorCode::eDEBUG_WARNING)
      ++failures;
  }
};
struct Context {
  PxDefaultAllocator allocator;
  Errors errors;
  PxFoundation *foundation = nullptr;
  PxPvd *debugger = nullptr;
  PxPvdTransport *transport = nullptr;
  void connect(const std::string &file) {
    foundation = PxCreateFoundation(PX_FOUNDATION_VERSION, allocator, errors);
    require(foundation != nullptr, "PxCreateFoundation failed");
    debugger = PxCreatePvd(*foundation);
    require(debugger != nullptr, "PxCreatePvd failed");
    transport = PxDefaultPvdFileTransportCreate(file.c_str());
    require(transport != nullptr, "file transport creation failed");
    require(debugger->connect(*transport, PxPvdInstrumentationFlag::ePROFILE),
            "ePROFILE connection failed");
  }
  ~Context() {
    if (debugger) {
      debugger->disconnect();
      debugger->release();
    }
    if (transport)
      transport->release();
    if (foundation)
      foundation->release();
  }
};
struct StreamGuard {
  wire::PvdDataStream *value;
  ~StreamGuard() {
    if (value)
      value->release();
  }
};

// Forward the real SDK-generated bytes unchanged. The inline SDK parser writes
// an oracle before the independent consumer ever reads the resulting capture.
struct Zone final : cpu::PxProfileZoneClient, cpu::PxProfileEventHandler {
  wire::PvdDataStream &stream;
  std::ofstream &oracle;
  cpu::PxProfileZone *zone = nullptr;
  bool attached = false, created = false;
  Zone(wire::PvdDataStream &s, std::ofstream &out,
       PxAllocatorCallback &allocator, const char *name,
       const cpu::PxProfileEventName *names, std::uint32_t count)
      : stream(s), oracle(out) {
    zone = &cpu::PxProfileZone::createProfileZone(
        &allocator, name, cpu::PxProfileNames(count, names), 1024);
    try {
      stream.addProfileZone(zone, name);
      checked(stream.createInstance(
          wire::NamespacedName("_debugger_", "PxProfileZone"), zone));
      created = true;
      for (std::uint32_t i = 0; i < count; ++i)
        handleEventAdded(names[i]);
      zone->addClient(*this);
      attached = true;
    } catch (...) {
      if (created)
        stream.destroyInstance(zone);
      zone->release();
      zone = nullptr;
      throw;
    }
  }
  ~Zone() {
    if (zone) {
      if (attached)
        zone->removeClient(*this);
      if (created)
        stream.destroyInstance(zone);
      zone->release();
    }
  }
  std::uint64_t id() const {
    return static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(zone));
  }
  void handleClientRemoved() override { attached = false; }
  void handleEventAdded(const cpu::PxProfileEventName &name) override {
    stream.addProfileZoneEvent(zone, name.name, name.eventId.eventId,
                               name.eventId.compileTimeEnabled);
  }
  void handleBufferFlush(const std::uint8_t *bytes,
                         std::uint32_t count) override {
    if (!count)
      return;
    require(cpu::parseEventData<false>(bytes, count, this),
            "SDK profile parser rejected its own buffer");
    checked(stream.setPropertyValue(zone, "events", bytes, count));
  }
  void record(const char *kind, const cpu::PxProfileEventId &event,
              std::uint32_t thread, std::uint64_t context, std::uint8_t cpu_id,
              std::uint8_t priority, std::uint64_t ticks,
              std::int64_t value = 0) {
    oracle << kind << ',' << id() << ',' << event.eventId << ',' << thread
           << ',' << context << ',' << unsigned(cpu_id) << ','
           << unsigned(priority) << ',' << ticks << ',' << value << '\n';
    require(bool(oracle), "SDK profile oracle output failed");
  }
  void onStartEvent(const cpu::PxProfileEventId &event, std::uint32_t thread,
                    std::uint64_t context, std::uint8_t cpu_id,
                    std::uint8_t priority, std::uint64_t ticks) override {
    record("start", event, thread, context, cpu_id, priority, ticks);
  }
  void onStopEvent(const cpu::PxProfileEventId &event, std::uint32_t thread,
                   std::uint64_t context, std::uint8_t cpu_id,
                   std::uint8_t priority, std::uint64_t ticks) override {
    record("stop", event, thread, context, cpu_id, priority, ticks);
  }
  void onEventValue(const cpu::PxProfileEventId &event, std::uint32_t thread,
                    std::uint64_t context, std::int64_t value) override {
    record("value", event, thread, context, 0, 0, 0, value);
  }
};
void generate(const std::filesystem::path &prefix) {
  if (!prefix.parent_path().empty())
    std::filesystem::create_directories(prefix.parent_path());
  std::ofstream oracle(prefix.string() + "_expected.csv");
  require(bool(oracle), "cannot create profile oracle CSV");
  oracle << "kind,zone,event,thread,context,cpu,priority,ticks,legacy_value\n";
  LARGE_INTEGER frequency{}, now{};
  require(QueryPerformanceFrequency(&frequency) != 0 &&
              QueryPerformanceCounter(&now) != 0,
          "QPC unavailable");
  oracle << "clock,1000000000," << frequency.QuadPart << "\n";
  Context context;
  context.connect(prefix.string() + "_capture.pxd2");
  auto *stream = wire::PvdDataStream::create(context.debugger);
  require(stream != nullptr, "PvdDataStream::create failed");
  StreamGuard guard{stream};
  const cpu::PxProfileEventName names[] = {
      {"Outer", 1},        {"Inner", 2},     {"Counter", 3},
      {"Cross packet", 4}, {"Reentrant", 5}, {"Other thread", 6}};
  {
    Zone main(*stream, oracle, context.allocator, "Fixture CPU", names, 6);
    const auto base = static_cast<std::uint64_t>(now.QuadPart);
    constexpr std::uint64_t context_id = 0x1122334455667788ull;
    main.zone->atEvent(1, context_id, 101, base + 100, base + 5100);
    main.zone->atEvent(2, context_id, 101, base + 5200, base + 5210);
    main.zone->atEvent(6, 0x1234, 202, base + 70000, base + 17000000);
    main.zone->eventValue(3, context_id, 70000);
    main.zone->flushProfileEvents();
    // A flush resets wire compression while the CPU scope remains open.
    main.zone->startEvent(4, context_id, 303);
    main.zone->flushProfileEvents();
    main.zone->stopEvent(4, context_id, 303);
    main.zone->startEvent(5, context_id, 303);
    main.zone->startEvent(5, context_id, 303);
    main.zone->stopEvent(5, context_id, 303);
    main.zone->stopEvent(5, context_id, 303);
    main.zone->flushProfileEvents();
    const cpu::PxProfileEventName worker_names[] = {{"Worker scope", 1}};
    Zone worker(*stream, oracle, context.allocator, "Fixture worker",
                worker_names, 1);
    worker.zone->atEvent(1, 42, 101, base + 300, base + 600);
    worker.zone->flushProfileEvents();
  }
  require(!context.errors.failures, "PhysX reported errors");
  oracle.flush();
  require(bool(oracle), "profile oracle flush failed");
  std::cout << "Generated " << prefix.string()
            << "_capture.pxd2 and SDK-parser oracle\n";
}
} // namespace
int main(int argc, char **argv) {
  Assertions handler;
  PxSetAssertHandler(handler);
  try {
    require(argc <= 2, "usage: physx34_profile_capture [output_prefix]");
    generate(argc == 2 ? std::filesystem::path(argv[1])
                       : std::filesystem::path("physx34_profile"));
    return 0;
  } catch (const std::exception &error) {
    std::cerr << "profile capture failed: " << error.what() << '\n';
    return 1;
  }
}
